def _set_base_font(document: Document) -> None:
    """设置中文字体，避免 Word 打开时中文回退成难看字形。"""
    try:
        style = document.styles["Normal"]
        style.font.name = "等线"
        style.font.size = Pt(10.5)
        rpr = style.element.get_or_add_rPr()
        fonts = rpr.find(qn("w:rFonts"))
        if fonts is None:
            fonts = rpr.makeelement(qn("w:rFonts"), {})
            rpr.append(fonts)
        fonts.set(qn("w:eastAsia"), "等线")
    except Exception:  # 字体设置失败不影响内容正确性
        pass


def build_document(spec: dict) -> Document:
    """按 spec 生成 docx 文档对象。

    不写一级标题：转换脚本会把文件名作为 H1，章节从 H2 起，与原有文献结构一致。
    文档标题写入 core properties，在 Word 属性面板仍可见。
    """
    document = Document()
    _set_base_font(document)
    document.core_properties.title = spec["title"]
    document.add_paragraph(spec["source_line"])
    for kind, payload in spec["blocks"]:
        if kind == "h2":
            document.add_heading(payload, level=2)
        elif kind == "h3":
            document.add_heading(payload, level=3)
        elif kind == "p":
            document.add_paragraph(payload)
        elif kind == "li":
            document.add_paragraph(payload, style="List Bullet")
        elif kind == "table":
            rows = payload
            table = document.add_table(rows=len(rows), cols=len(rows[0]))
            table.style = "Table Grid"
            for row_index, row in enumerate(rows):
                for col_index, value in enumerate(row):
                    table.cell(row_index, col_index).text = value
        else:
            raise ValueError(f"未知的块类型: {kind}")
    return document


def main() -> int:
    parser = argparse.ArgumentParser(description="生成补充文献 docx")
    parser.add_argument("--output", required=True, help="输出目录（原始文献目录）")
    parser.add_argument("--force", action="store_true", help="覆盖已存在的同名文件")
    args = parser.parse_args()

    output = Path(args.output)
    if not output.is_dir():
        print(f"目录不存在: {output}", flush=True)
        return 1

    created, skipped = [], []
    for spec in DOCUMENTS:
        target = output / spec["filename"]
        if target.exists() and not args.force:
            skipped.append(spec["filename"])
            continue
        build_document(spec).save(str(target))
        created.append(spec["filename"])

    print(f"生成 {len(created)} 篇，跳过 {len(skipped)} 篇（已存在）", flush=True)
    for name in created:
        print(f"  + {name}", flush=True)
    for name in skipped:
        print(f"  = {name}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
